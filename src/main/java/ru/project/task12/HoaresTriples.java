package ru.project.task12;

public class HoaresTriples {

    /**
     * Предусловие: a и b- целые числа, null не возможен.
     * Команда: гарантируется отсутствие сайд эффектов.
     * Постусловие: возвращается большее число. Если числа равны, то возвращается первый переданный аргумент.
     */
    public static int max(int a, int b) {
        return a >= b ? a : b;
    }

    /**
     * Предусловие: x - целое число, null не возможен.
     * Команда: гарантируется отсутствие сайд эффектов.
     * Постусловие: возвращается абсолютное значение x.
     */
    public static int abs(int x) {
        return x < 0 ? -x : x;
    }

    /**
     * Предусловие: a и b- целые числа, null не возможен.
     * Команда: гарантируется отсутствие сайд эффектов.
     * Постусловие: возвращает max(|a|, |b|)
     */
    public static int maxAbs(int a, int b) {
        return max(abs(a), abs(b));
    }

    public static void main(String[] args) {
        // оба положительные
        assert maxAbs(5, 3) == 5 : "Тест не пройден";

        // оба отрицательные
        assert maxAbs(-5, -3) == 5 : "Тест не пройден";

        // разные знаки
        assert maxAbs(-5, 3) == 5 : "Тест не пройден";

        // ноль и положительное
        assert maxAbs(0, 7) == 7 : "Тест не пройден";

        // ноль и отрицательное
        assert maxAbs(0, -7) == 7 : "Тест не пройден";

        // равные по модулю
        assert maxAbs(5, -5) == 5 : "Тест не пройден";

        System.out.println("Все тесты пройдены!");
    }
}
